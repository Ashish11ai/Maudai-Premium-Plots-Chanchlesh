function plotTo3D(plotNum) {
  const key = String(plotNum);
  const p = PLOT_POSITIONS[key];
  if (!p) return null;

  const polygon = Array.isArray(p.polygon) && p.polygon.length >= 3
    ? p.polygon
    : PLOT_POLYGONS_EXACT[key];

  if (Array.isArray(polygon) && polygon.length >= 3) {
    let minX = polygon[0][0];
    let maxX = polygon[0][0];
    let minZ = polygon[0][1];
    let maxZ = polygon[0][1];

    polygon.forEach(([x, z]) => {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (z < minZ) minZ = z;
      if (z > maxZ) maxZ = z;
    });

    return {
      x: (minX + maxX) / 2,
      z: (minZ + maxZ) / 2,
      width: maxX - minX,
      depth: maxZ - minZ,
      height: p.height,
      rotation: 0,
      polygon
    };
  }

  return {
    x: p.x,
    z: p.z,
    width: p.w,
    depth: p.h,
    height: p.height,
    rotation: p.rot
  };
}

